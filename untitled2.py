# Step 1: Import Libraries

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from google.colab import files

from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.impute import SimpleImputer

from sklearn.ensemble import RandomForestRegressor

from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

import warnings
warnings.filterwarnings("ignore")

print("Libraries imported successfully!")

# Step 2: Upload Dataset

import zipfile
import os

uploaded = files.upload()

# Find uploaded ZIP file
zip_file = None

for filename in uploaded.keys():
    if filename.endswith(".zip"):
        zip_file = filename
        break

if zip_file is None:
    raise FileNotFoundError("Please upload a ZIP file containing the dataset.")

# Extract ZIP
extract_folder = "car_dataset"

with zipfile.ZipFile(zip_file, 'r') as zip_ref:
    zip_ref.extractall(extract_folder)

print("ZIP file extracted successfully!")

# Find CSV file
csv_file = None

for root, dirs, files_list in os.walk(extract_folder):
    for file in files_list:
        if file.endswith(".csv"):
            csv_file = os.path.join(root, file)
            break

if csv_file is None:
    raise FileNotFoundError("No CSV file found inside the ZIP file.")

print("Dataset found:", csv_file)

# Load dataset
df = pd.read_csv(csv_file)

print("\nDataset loaded successfully!")
print("Shape:", df.shape)

# Step 3: Explore Dataset

print("First 5 rows:")
display(df.head())

print("\nDataset Information:")
print(df.info())

print("\nColumn Names:")
print(df.columns.tolist())

# Step 4: Check Missing Values and Statistics

print("Missing Values:")
print(df.isnull().sum())

print("\nStatistical Summary:")
display(df.describe())

# Step 5: Feature Engineering

# Create Brand from Car_Name
df["Brand"] = df["Car_Name"].str.split().str[0].str.lower()

# Create Car Age
CURRENT_YEAR = 2026
df["Car_Age"] = CURRENT_YEAR - df["Year"]

# Avoid zero age
df["Car_Age"] = df["Car_Age"].replace(0, 1)

# Log transformation of driven kilometers
df["Log_Driven_Kms"] = np.log1p(df["Driven_kms"])

# Average kilometers driven per year
df["Km_Per_Year"] = df["Driven_kms"] / df["Car_Age"]

print("Feature engineering completed!")

display(df.head())

# Step 6: Define Features and Target

X = df[
    [
        "Present_Price",
        "Driven_kms",
        "Year",
        "Fuel_Type",
        "Selling_type",
        "Transmission",
        "Owner",
        "Brand",
        "Car_Age",
        "Log_Driven_Kms",
        "Km_Per_Year"
    ]
]

y = df["Selling_Price"]

print("Features:")
print(X.columns.tolist())

print("\nTarget: Selling_Price")

print("\nX shape:", X.shape)
print("y shape:", y.shape)

# Step 7: Split Dataset into Training and Testing Sets

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

# Step 8: Data Preprocessing

numeric_features = [
    "Present_Price",
    "Driven_kms",
    "Year",
    "Owner",
    "Car_Age",
    "Log_Driven_Kms",
    "Km_Per_Year"
]

categorical_features = [
    "Fuel_Type",
    "Selling_type",
    "Transmission",
    "Brand"
]

numeric_transformer = Pipeline(
    steps=[
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler())
    ]
)

categorical_transformer = Pipeline(
    steps=[
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("onehot", OneHotEncoder(handle_unknown="ignore"))
    ]
)

preprocessor = ColumnTransformer(
    transformers=[
        ("num", numeric_transformer, numeric_features),
        ("cat", categorical_transformer, categorical_features)
    ]
)

print("Preprocessing pipeline created successfully!")

# Step 9: Create Machine Learning Model

model = RandomForestRegressor(
    n_estimators=300,
    max_depth=15,
    min_samples_split=2,
    min_samples_leaf=1,
    random_state=42
)

pipeline = Pipeline(
    steps=[
        ("preprocessor", preprocessor),
        ("model", model)
    ]
)

print("Random Forest Regression model created!")

# Step 10: Train Model

pipeline.fit(X_train, y_train)

print("Model training completed successfully!")

# Step 11: Make Predictions

y_pred = pipeline.predict(X_test)

print("Prediction completed!")

print("\nFirst 10 Predictions:")
for actual, predicted in zip(y_test.values[:10], y_pred[:10]):
    print(f"Actual Price: {actual:.2f} | Predicted Price: {predicted:.2f}")

# Step 12: Evaluate Model

mae = mean_absolute_error(y_test, y_pred)

rmse = np.sqrt(mean_squared_error(y_test, y_pred))

r2 = r2_score(y_test, y_pred)

print("========== MODEL EVALUATION ==========")

print(f"Mean Absolute Error (MAE): {mae:.4f}")

print(f"Root Mean Squared Error (RMSE): {rmse:.4f}")

print(f"R² Score: {r2:.4f}")

print("======================================")

# Step 13: Actual vs Predicted Price

plt.figure(figsize=(8, 6))

plt.scatter(y_test, y_pred)

plt.xlabel("Actual Car Price")
plt.ylabel("Predicted Car Price")
plt.title("Actual vs Predicted Car Prices")

# Perfect prediction line
min_price = min(y_test.min(), y_pred.min())
max_price = max(y_test.max(), y_pred.max())

plt.plot(
    [min_price, max_price],
    [min_price, max_price],
    linestyle="--"
)

plt.show()

# Step 14: Prediction Error

errors = y_test - y_pred

plt.figure(figsize=(8, 6))

plt.hist(errors, bins=20)

plt.xlabel("Prediction Error")
plt.ylabel("Frequency")
plt.title("Distribution of Prediction Errors")

plt.show()

# Step 15: Feature Importance

# Get transformed feature names
feature_names = pipeline.named_steps["preprocessor"].get_feature_names_out()

# Get feature importance
importances = pipeline.named_steps["model"].feature_importances_

importance_df = pd.DataFrame({
    "Feature": feature_names,
    "Importance": importances
})

importance_df = importance_df.sort_values(
    by="Importance",
    ascending=False
)

print("Top 15 Important Features:")

display(importance_df.head(15))

# Plot Top 10 Feature Importance

top_features = importance_df.head(10)

plt.figure(figsize=(10, 6))

plt.barh(
    top_features["Feature"][::-1],
    top_features["Importance"][::-1]
)

plt.xlabel("Importance")
plt.ylabel("Feature")
plt.title("Top 10 Feature Importance")

plt.show()

# Step 16: Predict Price of a New Car

new_car = pd.DataFrame({
    "Present_Price": [8.5],
    "Driven_kms": [30000],
    "Year": [2020],
    "Fuel_Type": ["Petrol"],
    "Selling_type": ["Dealer"],
    "Transmission": ["Manual"],
    "Owner": [0],
    "Brand": ["hyundai"],
    "Car_Age": [2026 - 2020],
    "Log_Driven_Kms": [np.log1p(30000)],
    "Km_Per_Year": [30000 / (2026 - 2020)]
})

predicted_price = pipeline.predict(new_car)

print("Predicted Car Selling Price:", round(predicted_price[0], 2))

# Step 17: Create Prediction Result Table

results = pd.DataFrame({
    "Actual_Price": y_test.values,
    "Predicted_Price": y_pred
})

results["Absolute_Error"] = abs(
    results["Actual_Price"] - results["Predicted_Price"]
)

display(results.head(15))